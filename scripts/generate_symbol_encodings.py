"""Dev-time generator for the Symbol/ZapfDingbats code->Unicode tables in
src/clearleaf/_encodings.py — NOT run at import time and NOT a runtime
dependency of clearleaf.

The data is the Unicode Consortium's official Adobe Symbol/ZapfDingbats
encoding mapping (unicode.org/Public/MAPPINGS/VENDORS/ADOBE/symbol.txt and
zapfdingbats.txt), which its license explicitly permits copying into other
software. `pypdf` (BSD-licensed) happens to bundle a convenient pre-parsed
Python copy of that same public data — this script reads it as a data
source, not as borrowed implementation logic:

    pip install pypdf
    python scripts/generate_symbol_encodings.py
"""

from pypdf._codecs.symbol import _symbol_encoding
from pypdf._codecs.zapfding import _zapfding_encoding


def _format_table(name: str, table: list) -> str:
    lines = [f"{name} = {{"]
    line = "    "
    for code, ch in enumerate(table):
        if not ch or ch == "\x00":
            continue
        piece = f"0x{code:02X}: {ch!r}, "
        if len(line) + len(piece) > 95:
            lines.append(line.rstrip())
            line = "    "
        line += piece
    if line.strip():
        lines.append(line.rstrip())
    lines.append("}")
    return "\n".join(lines)


_HEADER = '''"""Built-in code-to-Unicode encodings for the Symbol and ZapfDingbats
standard-14 fonts (ISO 32000-1:2008 9.6.6.2 — these two fonts don't use
StandardEncoding/WinAnsiEncoding/MacRomanEncoding at all; each has its own
fixed, font-specific encoding).

Generated by scripts/generate_symbol_encodings.py from the Unicode
Consortium's official Adobe Symbol/ZapfDingbats encoding mapping
(unicode.org/Public/MAPPINGS/VENDORS/ADOBE/{symbol,zapfdingbats}.txt),
whose license explicitly permits reuse in other software. A handful of
codes in each map to Private Use Area codepoints (U+F8xx / U+F6xx) for
glyphs (mostly bracket/parenthesis extender pieces) that have no standard
Unicode codepoint of their own — that's Adobe's own official mapping, not
an approximation introduced here.
"""'''


def main():
    print(_HEADER)
    print()
    print()
    print(_format_table("SYMBOL_ENCODING", _symbol_encoding))
    print()
    print(_format_table("ZAPF_DINGBATS_ENCODING", _zapfding_encoding))


if __name__ == "__main__":
    main()

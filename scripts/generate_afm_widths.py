"""Dev-time generator for src/clearleaf/_afm.py — NOT run at import time and
NOT a runtime dependency of clearleaf. Requires `pip install matplotlib`
(used only as a convenient vehicle for its bundled copy of Adobe's Core 14
AFM font metrics; those metrics, not matplotlib itself, are what ends up in
the generated module). Re-run and commit the output if these numbers ever
need refreshing:

    pip install matplotlib
    python scripts/generate_afm_widths.py > src/clearleaf/_afm.py
"""

import os
import re
import sys

import matplotlib

AFM_DIR = os.path.join(matplotlib.get_data_path(), "fonts", "afm")

FILES = {
    "Helvetica": "phvr8a.afm",
    "Helvetica-Bold": "phvb8a.afm",
    "Helvetica-Oblique": "phvro8a.afm",
    "Helvetica-BoldOblique": "phvbo8a.afm",
    "Times-Roman": "ptmr8a.afm",
    "Times-Bold": "ptmb8a.afm",
    "Times-Italic": "ptmri8a.afm",
    "Times-BoldItalic": "ptmbi8a.afm",
    "Courier": "pcrr8a.afm",
    "Courier-Bold": "pcrb8a.afm",
    "Courier-Oblique": "pcrro8a.afm",
    "Courier-BoldOblique": "pcrbo8a.afm",
    "Symbol": "psyr.afm",
    "ZapfDingbats": "pzdr.afm",
}

LINE_RE = re.compile(r"WX\s+(-?\d+)\s*;\s*N\s+(\S+)\s*;")


def main():
    out = {}
    for pdf_name, filename in FILES.items():
        widths = {}
        with open(os.path.join(AFM_DIR, filename)) as f:
            for line in f:
                if not line.startswith("C "):
                    continue
                m = LINE_RE.search(line)
                if m:
                    widths[m.group(2)] = int(m.group(1))
        out[pdf_name] = widths

    lines = []
    lines.append(
        '"""Adobe Core 14 font metrics (glyph name -> advance width, in 1/1000 em).'
    )
    lines.append("")
    lines.append("Used as the width fallback for the 14 standard PDF fonts (Helvetica/Times/")
    lines.append("Courier/Symbol/ZapfDingbats families) when a font dict has no /Widths array")
    lines.append("(i.e. the font isn't embedded and the viewer is expected to substitute one of")
    lines.append("these standard fonts) — ISO 32000-1:2008 9.6.2.2.")
    lines.append("")
    lines.append("Values are Adobe's own published Core 14 AFM metrics for these exact font")
    lines.append("names, which have been freely redistributed for this purpose (implementing")
    lines.append("PDF/PostScript text layout) by many independent open-source projects for")
    lines.append("decades — e.g. matplotlib, ReportLab, Ghostscript, X11. Generated by")
    lines.append("scripts/generate_afm_widths.py from matplotlib's bundled copy (dev-time")
    lines.append("only: matplotlib is not a runtime dependency of clearleaf); not derived from")
    lines.append('MuPDF/PyMuPDF in any way.\n"""')
    lines.append("")
    lines.append("STANDARD_FONT_WIDTHS = {")
    for pdf_name, widths in out.items():
        lines.append(f"    {pdf_name!r}: {{")
        items = sorted(widths.items())
        line = "        "
        for gname, w in items:
            piece = f"{gname!r}: {w}, "
            if len(line) + len(piece) > 95:
                lines.append(line.rstrip())
                line = "        "
            line += piece
        if line.strip():
            lines.append(line.rstrip())
        lines.append("    },")
    lines.append("}")
    lines.append("")
    sys.stdout.write("\n".join(lines))


if __name__ == "__main__":
    main()
